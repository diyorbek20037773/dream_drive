router = APIRouter(prefix="/jobs", tags=["jobs"])
logger = logging.getLogger("dreamdrive.api.jobs")

_BINARY: dict[str, Any] = {"schema": {"type": "string", "format": "binary"}}
# report.html is generated by the pipeline; served sandboxed anyway so it can never script this origin.
_HTML_CSP = "default-src 'none'; img-src data:; style-src 'unsafe-inline'; sandbox"
# Always stated for uploaded-video results (docs/PRODUCT.md, CLAUDE.md); report.json adds model-specific ones.
API_LIMITATIONS_VIDEO: tuple[str, ...] = (
    "The uploaded video is an observation recording: decisions are analytical only and cannot change its next frame.",
    "Detector scores are model confidence, not a safety probability.",
    "No actuator command is produced or sent to any vehicle.",
)


def _not_found() -> ApiError:
    return ApiError(404, ErrorCode.NOT_FOUND, "Job not found")


def _owned_job(services: Services, owner_id: str, job_id: str) -> repo.JobRow:
    row = repo.get_job(services.db, owner_id, job_id)
    if row is None:
        raise _not_found()
    return row


def _signal_cancel(services: Services, job_id: str) -> None:
    try:
        services.redis.set(job_cancel_key(job_id), b"1", ex=JOB_CANCEL_TTL_S)
    except redis.RedisError:
        logger.warning("cancel key not set; worker falls back to the DB flag", extra={"code": "redis_error"})


def _publish_state(services: Services, row: repo.JobRow, state: str) -> None:
    services.bus.publish(row.owner_id, "job_state", row.id, {"job_id": row.id, "state": state, "error_code": None})


def _cancel_queued(services: Services, row: repo.JobRow) -> bool:
    """queued -> cancelled before any worker started it. False if a worker claimed it meanwhile."""
    if not repo.transition_job(
        services.db, row.id, ("queued",), "cancelled", stage="cancelled", finished_utc=utc_now()
    ):
        return False
    try:
        cancel_if_queued(services.redis, rq_video_id(row.id))
    except redis.RedisError:
        # The worker skips jobs that are no longer `queued` in SQLite, so a leftover RQ entry is harmless.
        logger.warning("RQ cancel failed for a cancelled job", extra={"code": "redis_error"})
    metrics.JOBS_TOTAL.labels("video_analysis", "cancelled").inc()
    _publish_state(services, row, "cancelled")
    return True


@router.get("", response_model=JobList, summary="List the caller's jobs", responses=error_responses(401, 422))
def list_jobs(
    request: Request,
    session: SessionDep,
    settings: SettingsDep,
    limit: PageLimit = 20,
    cursor: PageCursor = None,
) -> JobList:
    """Newest first, bounded page size."""
    services = get_services(request)
    rows = repo.list_jobs(services.db, session.session_id, limit + 1, decode_cursor(cursor))
    page = rows[:limit]
    next_cursor = encode_cursor(page[-1].created_utc, page[-1].id) if len(rows) > limit else None
    return JobList(items=[job_to_api(r, settings) for r in page], next_cursor=next_cursor)


@router.get(
    "/{job_id}",
    response_model=Job,
    summary="Job state, progress, error and model identity",
    responses=error_responses(401, 404, 422),
)
def get_job(request: Request, job_id: JobIdPath, session: SessionDep, settings: SettingsDep) -> Job:
    return job_to_api(_owned_job(get_services(request), session.session_id, job_id), settings)


@router.post(
    "/{job_id}/cancel",
    response_model=Job,
    summary="Request cancellation (idempotent)",
    responses=error_responses(401, 403, 404, 422),
)
def cancel_job(request: Request, job_id: JobIdPath, session: CsrfSessionDep, settings: SettingsDep) -> Job:
    """Queued jobs become `cancelled`; running jobs become `cancelling` until the worker stops between frames.
    Terminal jobs are returned unchanged."""
    services = get_services(request)
    row = _owned_job(services, session.session_id, job_id)
    if row.state == "queued" and _cancel_queued(services, row):
        return job_to_api(_owned_job(services, session.session_id, job_id), settings)
    row = _owned_job(services, session.session_id, job_id)
    if row.state in ("validating", "running"):
        repo.transition_job(services.db, job_id, ("validating", "running"), "cancelling", cancel_requested=True)
        _signal_cancel(services, job_id)
        _publish_state(services, row, "cancelling")
        logger.info("cancellation requested", extra={"job_id": job_id, "code": "cancel_requested"})
    return job_to_api(_owned_job(services, session.session_id, job_id), settings)


@router.get(
    "/{job_id}/results",
    response_model=JobResults,
    summary="Structured result summary and artifact links",
    responses=error_responses(401, 404, 409, 422),
)
def get_job_results(request: Request, job_id: JobIdPath, session: SessionDep, settings: SettingsDep) -> JobResults:
    """409 `results_unavailable` until the job has succeeded."""
    services = get_services(request)
    row = _owned_job(services, session.session_id, job_id)
    if row.state != "succeeded" or row.summary is None:
        raise ApiError(
            409, ErrorCode.RESULTS_UNAVAILABLE, "Results are available once the job has succeeded", {"state": row.state}
        )
    try:
        summary = JobSummary.model_validate(row.summary)
    except ValidationError as exc:
        logger.error("stored summary invalid", extra={"job_id": job_id, "code": "summary_invalid"})
        raise ApiError(
            409, ErrorCode.RESULTS_UNAVAILABLE, "Stored results are unreadable", {"state": row.state}
        ) from exc
    listed: list[JobArtifact] = []
    timeline_url = None
    for name in artifacts.RESULT_ARTIFACTS:
        found = artifacts.artifact_file(settings.artifact_root, job_id, name, row.input_ext)
        if found is None:
            continue
        url = f"/api/v1/jobs/{job_id}/artifacts/{name}"
        listed.append(JobArtifact(name=name, url=url, content_type=found.content_type, bytes=found.size))  # type: ignore[arg-type]
        if name == "timeline.json":
            timeline_url = url
    limitations = list(API_LIMITATIONS_VIDEO)
    report = artifacts.artifact_file(settings.artifact_root, job_id, "report.json", row.input_ext)
    if report is not None:
        try:
            extra = json.loads(report.path.read_text(encoding="utf-8")).get("limitations", [])
            limitations.extend(str(x) for x in extra if isinstance(x, str) and str(x) not in limitations)
        except (OSError, ValueError, AttributeError):
            logger.warning("report.json unreadable", extra={"job_id": job_id})
    model = None
    if row.model:
        try:
            model = ModelIdentity.model_validate(row.model)
        except ValidationError:
            model = None
    return JobResults(
        job_id=job_id,
        state="succeeded",
        perception_source="learned_model",
        model=model,
        summary=summary,
        artifacts=listed,
        timeline_url=timeline_url,
        limitations=limitations,
    )


@router.get(
    "/{job_id}/artifacts/{name}",
    response_class=Response,
    summary="Download an allowlisted artifact (byte ranges supported)",
    responses={
        200: {
            "description": "Artifact bytes",
            "content": {
                "video/mp4": _BINARY,
                "video/quicktime": _BINARY,
                "application/json": _BINARY,
                "text/html": _BINARY,
                "image/jpeg": _BINARY,
            },
            "headers": {"Accept-Ranges": {"schema": {"type": "string"}, "description": "bytes"}},
        },
        206: {
            "description": "Partial content for a satisfiable Range request",
            "content": {"video/mp4": _BINARY, "video/quicktime": _BINARY},
            "headers": {"Content-Range": {"schema": {"type": "string"}, "description": "bytes start-end/total"}},
        },
        **error_responses(401, 404, 409, 416, 422),
    },
)
def get_job_artifact(
    request: Request,
    job_id: JobIdPath,
    name: ArtifactName,
    session: SessionDep,
    settings: SettingsDep,
    range_header: Annotated[str | None, Header(alias="Range", max_length=128)] = None,
) -> Response:
    """Only allowlisted names; owner-checked. 409 `artifact_unavailable` while the job has not produced it."""
    services = get_services(request)
    row = _owned_job(services, session.session_id, job_id)
    found = artifacts.artifact_file(settings.artifact_root, job_id, name, row.input_ext)
    if found is None:
        raise ApiError(
            409,
            ErrorCode.ARTIFACT_UNAVAILABLE,
            "This artifact is not available for the job",
            {"state": row.state, "name": name},
        )
    download = (
        f"dreamdrive-{job_id[:8]}-input.{row.input_ext}" if name == "input" else f"dreamdrive-{job_id[:8]}-{name}"
    )
    extra = {"Content-Security-Policy": _HTML_CSP} if name == "report.html" else None
    try:
        return artifacts.file_response(found, range_header, download, extra)
    except artifacts.RangeNotSatisfiable as exc:
        raise ApiError(
            416,
            ErrorCode.RANGE_NOT_SATISFIABLE,
            "Requested range not satisfiable",
            {"size_bytes": exc.size},
            headers={"Content-Range": f"bytes */{exc.size}"},
        ) from exc


@router.delete(
    "/{job_id}",
    response_model=DeleteResult,
    summary="Delete a job and its bytes (idempotent)",
    responses=error_responses(401, 403, 404, 422),
)
def delete_job(request: Request, job_id: JobIdPath, session: CsrfSessionDep, settings: SettingsDep) -> DeleteResult:
    """In-progress jobs are cancelled first and their bytes removed once the worker stops."""
    services = get_services(request)
    owner = session.session_id
    row = repo.get_job_any(services.db, job_id)
    if row is None or row.owner_id != owner:
        if repo.has_job_tombstone(services.db, owner, job_id):
            return DeleteResult(id=job_id, status="deleted")
        raise _not_found()
    if row.delete_requested and not row.terminal:
        return DeleteResult(id=job_id, status="deletion_scheduled")
    if row.state == "queued":
        _cancel_queued(services, row)
        row = repo.get_job_any(services.db, job_id) or row
    if not row.terminal:
        repo.transition_job(
            services.db, job_id, ("validating", "running"), "cancelling", cancel_requested=True, delete_requested=True
        )
        repo.update_job(services.db, job_id, cancel_requested=True, delete_requested=True)
        _signal_cancel(services, job_id)
        current = repo.get_job_any(services.db, job_id)
        if current is not None and not current.terminal:
            logger.info("deletion scheduled", extra={"job_id": job_id, "code": "delete_scheduled"})
            return DeleteResult(id=job_id, status="deletion_scheduled")
        # The worker finished in between and may have missed the flag: remove it here.
    removed = artifacts.remove_job_artifacts(settings.artifact_root, job_id)
    repo.delete_job_row(services.db, job_id, owner)
    logger.info("job deleted", extra={"job_id": job_id, "code": "job_deleted", "removed_bytes": removed})
    return DeleteResult(id=job_id, status="deleted")
