#!/usr/bin/env bash
# Pull-only smoke of PUBLISHED images (make smoke-published): a fresh Compose project from compose.prod.yaml with
# images referenced only by registry digest, fresh named volumes, model-init (download + SHA256 verify), health
# waits and the HTTPS smoke (DOMAIN=localhost, Caddy internal CA) — exactly the deploy.sh path, on this machine.
# No source mounts, no local builds, no host Python/Node inside the stack (the smoke client itself needs python3).
#
#   scripts/smoke-published.sh --release artifacts/release/<commit>/release.env [--upload clip.mp4] [--keep]
#
# --keep leaves the project running; otherwise it and ITS OWN volumes are removed afterwards.
# Evidence: artifacts/smoke-published/<stamp>/ (or DD_EVIDENCE_DIR).
set -Eeuo pipefail
DD_LOG_TAG=smoke-published
# shellcheck source=deploy/lib/common.sh
source "$(dirname "${BASH_SOURCE[0]}")/../deploy/lib/common.sh"

release="" upload="" keep=0 fresh=1
while (($#)); do
  case $1 in
    --release) release=$2; shift 2 ;;
    --upload) upload=$2; shift 2 ;;
    --keep) keep=1; shift ;;
    --no-fresh) fresh=0; shift ;;
    -h | --help) sed -n '2,10p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1" 64 ;;
  esac
done
[[ -f $release ]] || die "--release FILE is required (scripts/release-manifest.sh writes it)" 64

stamp=$(date -u +%Y%m%d%H%M%S)
work="${DD_EVIDENCE_DIR:-$DD_REPO_ROOT/artifacts/smoke-published/$stamp}"
mkdir -p "$work"
project="dreamdrive-pubsmoke-$stamp"
env_file="$work/local.env"
umask 077
cat >"$env_file" <<EOF
# Generated by scripts/smoke-published.sh for a local pull-only smoke. Not a production file.
APP_ENV=production
DOMAIN=localhost
PUBLIC_ORIGIN=https://localhost:${DD_SMOKE_HTTPS_PORT:-18443}
APP_SECRET=$(head -c 48 /dev/urandom | base64 | tr -d '\n=' | tr '+/' '-_')
DD_PUBLIC_BIND=127.0.0.1
DD_PUBLIC_HTTP_PORT=${DD_SMOKE_HTTP_PORT:-18080}
DD_PUBLIC_HTTPS_PORT=${DD_SMOKE_HTTPS_PORT:-18443}
EOF
chmod 600 "$env_file" 2>/dev/null || warn "could not chmod 600 $env_file"

clear_release_env
load_env_file "$release"
namespace=${DOCKERHUB_NAMESPACE:-diyorbek7377}
refs=("$namespace/dreamdrive-web@${WEB_IMAGE_DIGEST:-}" "$namespace/dreamdrive-backend@${BACKEND_IMAGE_DIGEST:-}"
  "$namespace/dreamdrive-inference@${INFERENCE_IMAGE_DIGEST:-}")

if ((fresh)); then
  # Drop local copies of these exact digests so the run really pulls from the registry.
  for ref in "${refs[@]}"; do
    if docker image inspect "$ref" >/dev/null 2>&1; then
      docker image rm "$ref" >/dev/null 2>&1 || warn "could not remove local $ref (in use); it will be reused"
    fi
  done
fi

cleanup() {
  local rc=$?
  if ((keep)); then
    log "keeping project $project (stop with: docker compose -p $project down -v)"
  elif [[ $project == dreamdrive-pubsmoke-* ]]; then
    dd_compose_setup prod "$project" "$env_file" "$release"
    "${DD_COMPOSE[@]}" down --volumes --remove-orphans >/dev/null 2>&1 || warn "could not remove $project"
  fi
  rm -f "$env_file"
  exit "$rc"
}
trap cleanup EXIT

deploy_args=(--env-file "$env_file" --release "$release" --local --project "$project")
[[ -n $upload ]] && deploy_args+=(--smoke-upload "$upload")
DD_STATE_DIR="$work/state" bash "$DD_REPO_ROOT/deploy/deploy.sh" "${deploy_args[@]}"

# The pulled images must carry the release commit in their OCI labels.
for ref in "${refs[@]}"; do
  label=$(docker image inspect --format '{{index .Config.Labels "org.opencontainers.image.revision"}}' "$ref")
  [[ $label == "$GIT_COMMIT" ]] || die "$ref has revision label '$label', expected $GIT_COMMIT"
done
log "image revision labels match $GIT_COMMIT"
find "$work/state/history" -name smoke.json -exec cp {} "$work/smoke.json" \;
cp "$release" "$work/release.env"
log "published-image smoke passed; evidence in $work"
